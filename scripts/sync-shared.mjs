#!/usr/bin/env node
// Copies packages/core/src into supabase/functions/_shared/core so Edge Functions bundle it on deploy
// (the Supabase bundler only includes files under supabase/functions). Run after editing packages/core.
import { cpSync, rmSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "packages/core/src");
const dest = join(root, "supabase/functions/_shared/core");
rmSync(dest, { recursive: true, force: true });
mkdirSync(dest, { recursive: true });
cpSync(src, dest, { recursive: true });
writeFileSync(join(dest, "README.md"), "Generated by `npm run sync:shared` from packages/core/src. Do not edit here.\n");
console.log(`synced ${src} -> ${dest}`);
